$(document).ready(function() {
    $('.search_list').hide();
    $('.search').on('keyup', function() {
        var query = $(this).val();
        if (query.length <= 0) {
            $('.search_list').hide();
        } else {
            $.ajax({
                url: "search",
                type: "GET",
                data: {
                    'search': query
                },
                success: function(data) {
                    $('.search_list').show();
                    $('.search_list').html(data);
                }
            });
        }

    });
});
   </script>

